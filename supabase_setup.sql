-- Customers place orders only through this function; price and total are looked up server-side.
create or replace function public.place_order(order_data jsonb)
returns bigint language plpgsql security definer set search_path = public, pg_temp as $$
declare
  new_id bigint;
  calculated_total numeric(12,2) := 0;
  normalized_items jsonb := '[]'::jsonb;
  it jsonb;
  p public.products%rowtype;
  q integer;
  customer_name_value text := trim(coalesce(order_data->>'customer_name',''));
  customer_phone_value text := trim(coalesce(order_data->>'customer_phone',''));
  address_value text := trim(coalesce(order_data->>'delivery_address',''));
begin
  if length(customer_name_value) < 2 or length(customer_name_value) > 120 then raise exception 'Please provide a valid customer name'; end if;
  if length(customer_phone_value) < 7 or length(customer_phone_value) > 30 then raise exception 'Please provide a valid phone number'; end if;
  if length(address_value) < 5 or length(address_value) > 1000 then raise exception 'Please provide a valid delivery address'; end if;
  if jsonb_typeof(order_data->'items') <> 'array' or jsonb_array_length(order_data->'items') < 1 or jsonb_array_length(order_data->'items') > 50 then raise exception 'Invalid order items'; end if;
  for it in select value from jsonb_array_elements(order_data->'items') loop
    if (it->>'product_id') !~ '^\d+$' or (it->>'quantity') !~ '^\d+$' then raise exception 'Invalid product or quantity'; end if;
    q := (it->>'quantity')::integer;
    if q < 1 or q > 100 then raise exception 'Invalid quantity'; end if;
    select * into p from public.products where id = (it->>'product_id')::bigint and active = true for update;
    if not found then raise exception 'A product is no longer available'; end if;
    if p.stock < q then raise exception 'Not enough stock for: %', p.name; end if;
    calculated_total := calculated_total + p.price * q;
    normalized_items := normalized_items || jsonb_build_array(jsonb_build_object('product_id',p.id,'product_name',p.name,'unit_price',p.price,'quantity',q,'line_total',p.price*q));
  end loop;
  insert into public.orders(customer_name,customer_phone,delivery_address,total_amount,status,items)
  values(customer_name_value,customer_phone_value,address_value,calculated_total,'new',normalized_items) returning id into new_id;
  for it in select value from jsonb_array_elements(normalized_items) loop
    update public.products set stock = stock - (it->>'quantity')::integer, updated_at = now() where id = (it->>'product_id')::bigint;
  end loop;
  return new_id;
end; $$;
revoke all on function public.place_order(jsonb) from public;
grant execute on function public.place_order(jsonb) to anon, authenticated;
